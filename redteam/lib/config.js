/**
 * promptfoo config generation.
 *
 * One provider per probe (a custom JS provider — see runners/probe-provider.js
 * for why the built-in HTTP provider cannot be used) and one test per probe,
 * scoped to its provider with `providers: [<label>]`. promptfoo resolves that
 * label against its configured-provider map; a bare `provider:` string is
 * instead loaded as a new provider path, which is why we use the plural form.
 */
const { toYaml } = require('./yaml');

const PROVIDER_FILE = 'probe-provider.js';

function buildConfigText(target, probes, nonce) {
  // Every probe URL carries the run nonce so nothing downstream can answer a
  // rerun from a cache.
  const providers = probes.map((probe) => {
    const url = new URL(probe.path, target.base);
    url.searchParams.set('__redteam_probe', probe.id);
    url.searchParams.set('__redteam_run', nonce);
    return {
      id: `file://${PROVIDER_FILE}`,
      label: probe.id,
      config: {
        probe: probe.id,
        url: url.toString(),
        method: probe.method,
        headers: {
          'user-agent': 'fuse-hub-redteam/1.0',
          'x-redteam-probe': probe.id,
          'x-redteam-run': nonce,
          ...(probe.headers || {}),
        },
        ...(probe.body === undefined ? {} : { body: probe.body }),
      },
    };
  });

  const tests = probes.map((probe) => ({
    providers: [probe.id],
    description: probe.what,
    vars: { probe: probe.id },
    assert: probe.checks.map((check) => ({
      type: 'javascript',
      value: 'file://assertions/invariants.js',
      config: { check, probe: probe.id },
    })),
  }));

  const config = {
    description: `fleet hardening scan — ${target.name} (${target.base})`,
    prompts: ['redteam probe: {{probe}}'],
    providers,
    tests,
  };

  return `# Generated by redteam/server.js — ${new Date().toISOString()}\n${toYaml(config)}\n`;
}

module.exports = { PROVIDER_FILE, buildConfigText };
